    def embed_image(self, path: str, caption: str = "", max_w: int = 150):
        try:
            from PIL import Image as PILImage
            with PILImage.open(path) as im:
                iw, ih = im.size
            aspect = ih / iw
            w = min(max_w, CONTENT_W)
            h = w * aspect
            if self.get_y() + h + 10 > PAGE_H - 20:
                self.add_page()
            
            x = MARGIN + (CONTENT_W - w) / 2
            
            # Draw a subtle border around the image
            self.set_draw_color(220, 220, 220)
            self.set_line_width(0.3)
            self.rect(x - 1, self.get_y() - 1, w + 2, h + 2, "D")
            
            self.image(path, x=x, y=None, w=w)
            if caption:
                self.ln(1)
                self.set_font("Arial", "I", 8)
                self.set_text_color(*MID_GRAY)
                self.cell(CONTENT_W, 5, self._safe_str(caption), ln=True, align="C")
            self.ln(4)
        except Exception:
            self.set_font("Arial", "I", 9)
            self.set_text_color(*LIGHT_GRAY)
            self.cell(CONTENT_W, 6, f"[Image unavailable: {caption}]", ln=True)
            self.ln(2)

